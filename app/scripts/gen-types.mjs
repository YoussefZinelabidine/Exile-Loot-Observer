// Generates src/lib/snapshot/types.generated.ts from shared/schema/*.schema.json.
// Run with `pnpm gen:types`. A Vitest test fails when the committed file is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const appRoot = fileURLToPath(new URL("..", import.meta.url));
const schemaDir = fileURLToPath(new URL("../../shared/schema/", import.meta.url));
export const outputPath = fileURLToPath(new URL("../src/lib/snapshot/types.generated.ts", import.meta.url));

// One namespace per schema: the schemas reuse $defs names, so a flat file would clash.
const schemas = [
  ["Manifest", "manifest.schema.json"],
  ["Patch", "patch.schema.json"],
  ["Daily", "daily.schema.json"],
  ["GoldenExpected", "golden-expected.schema.json"],
];

export async function generate() {
  let out =
    "/* eslint-disable */\n" +
    "// GENERATED by `pnpm gen:types` from shared/schema/*.schema.json. Do not edit by hand.\n\n";
  for (const [ns, file] of schemas) {
    const schema = JSON.parse(readFileSync(schemaDir + file, "utf8"));
    const ts = await compile(schema, ns, {
      bannerComment: "",
      cwd: schemaDir,
      additionalProperties: false,
      style: { singleQuote: false },
    });
    out += `export namespace ${ns} {\n${ts.trimEnd()}\n}\n\n`;
  }
  return out.trimEnd().replace(/\r\n/g, "\n") + "\n";
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(outputPath, await generate());
  console.log("wrote " + outputPath);
}
