"""Generate ``backend/common/snapshot_models.py`` from ``shared/schema/*.schema.json``.

Run ``python -m backend.common.gen_models`` after changing a schema. A test fails when the
committed file is out of date (``--check`` does the same from the command line).

The four schemas are merged into one document first: every schema becomes one definition
(``Manifest``, ``Patch``, ``Daily``, ``GoldenExpected``) and its local ``$defs`` are prefixed
with the schema name, so class names never collide. The field named ``schema`` is renamed by
the generator to ``schema_`` with an alias, because it shadows a ``BaseModel`` attribute.
Parse JSON by ``schema`` (or build by ``schema_``, population by field name is on) and always
serialise with ``model_dump(by_alias=True)`` so the output says ``schema`` again.
"""

import json
import re
import sys
from pathlib import Path

from datamodel_code_generator import (
    DataModelType,
    Formatter,
    InputFileType,
    PythonVersion,
    generate,
)

from backend.common.config import REPO_ROOT

SCHEMA_DIR = REPO_ROOT / "shared" / "schema"
OUTPUT = REPO_ROOT / "backend" / "common" / "snapshot_models.py"

# schema file -> root definition name
SCHEMAS = {
    "manifest.schema.json": "Manifest",
    "patch.schema.json": "Patch",
    "daily.schema.json": "Daily",
    "golden-expected.schema.json": "GoldenExpected",
}

HEADER = (
    "# ruff: noqa\n"
    "# Generated by `python -m backend.common.gen_models` from shared/schema/*.schema.json.\n"
    "# Do not edit by hand."
)

_REF = re.compile(r"^#/\$defs/(.+)$")


def _prefix_refs(node, prefix: str, root_name: str):
    if isinstance(node, dict):
        out = {}
        for key, value in node.items():
            if key == "$ref" and isinstance(value, str):
                match = _REF.match(value)
                if match:
                    out[key] = f"#/$defs/{prefix}_{match.group(1)}"
                elif value == "#":
                    out[key] = f"#/$defs/{root_name}"
                else:
                    out[key] = value
            else:
                out[key] = _prefix_refs(value, prefix, root_name)
        return out
    if isinstance(node, list):
        return [_prefix_refs(item, prefix, root_name) for item in node]
    return node


def merged_schema() -> dict:
    defs: dict = {}
    for filename, root_name in SCHEMAS.items():
        schema = json.loads((SCHEMA_DIR / filename).read_text(encoding="utf-8"))
        prefix = root_name[0].lower() + root_name[1:]
        local_defs = schema.pop("$defs", {})
        for meta in ("$schema", "$id"):
            schema.pop(meta, None)
        for name, definition in local_defs.items():
            defs[f"{prefix}_{name}"] = _prefix_refs(definition, prefix, root_name)
        defs[root_name] = _prefix_refs(schema, prefix, root_name)
    return {"$schema": "https://json-schema.org/draft/2020-12/schema", "$defs": defs}


def generate_source() -> str:
    from tempfile import TemporaryDirectory

    with TemporaryDirectory() as tmp:
        out = Path(tmp) / "snapshot_models.py"
        generate(
            json.dumps(merged_schema()),
            input_file_type=InputFileType.JsonSchema,
            output=out,
            output_model_type=DataModelType.PydanticV2BaseModel,
            target_python_version=PythonVersion.PY_312,
            use_standard_collections=True,
            use_annotated=True,
            field_constraints=True,
            use_schema_description=True,
            disable_timestamp=True,
            allow_population_by_field_name=True,
            custom_file_header=HEADER,
            formatters=[Formatter.BUILTIN],
        )
        return out.read_text(encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    args = sys.argv[1:] if argv is None else argv
    source = generate_source()
    if "--check" in args:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != source:
            print("snapshot_models.py is out of date; run python -m backend.common.gen_models")
            return 1
        return 0
    OUTPUT.write_text(source, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
